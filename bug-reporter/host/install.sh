#!/usr/bin/env bash
# eGov Bug Reporter — registers the local helper with Chrome-based browsers.
# Safe to re-run (e.g. after moving the folder or upgrading gh / Claude Code).
#
#   ./install.sh                 register the helper and check gh / Claude Code
#   ./install.sh --install-skill also link the drafting skill into ~/.claude/skills
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(dirname "$HERE")"
HOST_NAME="com.egov.bug_reporter"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/egov-bug-reporter"
INSTALL_SKILL=0
[ "${1:-}" = "--install-skill" ] && INSTALL_SKILL=1

ok()     { printf '  \033[32m✓\033[0m %s\n' "$*"; }
warn()   { printf '  \033[33m!\033[0m %s\n' "$*"; }
bad()    { printf '  \033[31m✗\033[0m %s\n' "$*"; }
fixcmd() { printf '      run:  \033[1m%s\033[0m\n' "$*"; }

find_bin() {
  local name="$1" p
  p="$(command -v "$name" 2>/dev/null || true)"
  if [ -z "$p" ]; then
    for d in "$HOME/.local/bin" /opt/homebrew/bin /usr/local/bin /usr/bin; do
      if [ -x "$d/$name" ]; then p="$d/$name"; break; fi
    done
  fi
  printf '%s' "$p"
}

echo "eGov Bug Reporter — helper setup"
echo

# ---- Node ----
NODE="$(find_bin node)"
if [ -z "$NODE" ]; then bad "Node.js 18+ not found"; fixcmd "brew install node"; exit 1; fi
NODE_MAJOR="$("$NODE" -p 'process.versions.node.split(".")[0]')"
if [ "$NODE_MAJOR" -lt 18 ]; then bad "Node $("$NODE" -v) is too old (need 18+)"; fixcmd "brew upgrade node"; exit 1; fi
ok "Node $("$NODE" -v)  ($NODE)"

PROBLEMS=0

# ---- GitHub CLI ----
GH="$(find_bin gh)"
if [ -z "$GH" ]; then
  bad "GitHub CLI (gh) not found"; fixcmd "brew install gh"; fixcmd "gh auth login"; fixcmd "gh auth refresh -s project,read:project"; PROBLEMS=1
else
  ok "gh $("$GH" --version | head -1 | awk '{print $3}')  ($GH)"
  GH_HELP="$("$GH" issue create --help 2>&1 || true)"
  if ! grep -q -- '--attach' <<<"$GH_HELP"; then
    warn "this gh version can't upload screenshots/videos (needs --attach)"; fixcmd "brew upgrade gh"; PROBLEMS=1
  fi
  AUTH="$("$GH" auth status --hostname github.com 2>&1 || true)"
  if ! grep -q "Logged in to github.com" <<<"$AUTH"; then
    bad "gh is not logged in"; fixcmd "gh auth login"; fixcmd "gh auth refresh -s project,read:project"; PROBLEMS=1
  elif ! grep -Eq "Token scopes:.*'project'" <<<"$AUTH"; then
    bad "gh login is missing the 'project' scope"; fixcmd "gh auth refresh -s project,read:project"; PROBLEMS=1
  else
    ok "gh is logged in with the 'project' scope"
  fi
fi

# ---- Claude Code ----
CLAUDE="$(find_bin claude)"
if [ -z "$CLAUDE" ]; then
  bad "Claude Code (claude) not found"; fixcmd "install Claude Code, then: claude auth login"; PROBLEMS=1
else
  ok "Claude Code $("$CLAUDE" --version 2>/dev/null | awk '{print $1}')  ($CLAUDE)"
  STATUS="$(env -u ANTHROPIC_API_KEY "$CLAUDE" auth status --json 2>/dev/null || true)"
  read -r LOGGED METHOD < <(printf '%s' "$STATUS" | "$NODE" -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{try{const j=JSON.parse(s);console.log(j.loggedIn?"yes":"no",j.authMethod||"-")}catch{console.log("no -")}})')
  if [ "$LOGGED" = "yes" ]; then
    ok "Claude Code is signed in (auth: $METHOD)"
  else
    bad "Claude Code is not signed in (drafting with Claude won't work until it is)"; fixcmd "claude auth login"; PROBLEMS=1
  fi
fi

# ---- helper config + launcher ----
mkdir -p "$CONFIG_DIR"
"$NODE" -e '
const fs = require("fs");
const [file, node, gh, claude, repo] = process.argv.slice(1);
fs.writeFileSync(file, JSON.stringify({ node, gh: gh || null, claude: claude || null, repo }, null, 2) + "\n");
' "$CONFIG_DIR/config.json" "$NODE" "$GH" "$CLAUDE" "$REPO"

# Copy the helper out of this folder: on macOS, Desktop/Documents/Downloads are
# privacy-protected, and a helper Chrome starts from there would hang on a
# folder-access prompt. Re-run this script after updating the bug-reporter folder.
if [ "$(uname)" = "Darwin" ]; then
  APP_DIR="$HOME/Library/Application Support/egov-bug-reporter"
else
  APP_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/egov-bug-reporter"
fi
mkdir -p "$APP_DIR"
rm -rf "$APP_DIR/host" "$APP_DIR/skill"
cp -R "$HERE" "$APP_DIR/host"
cp -R "$REPO/skill" "$APP_DIR/skill"
ok "Helper copied to $APP_DIR"

LAUNCHER="$CONFIG_DIR/run-host.sh"
{
  printf '#!/bin/sh\n'
  printf '# Generated by %s — re-run it after updating the bug-reporter folder.\n' "$HERE/install.sh"
  printf 'exec "%s" "%s" "$@"\n' "$NODE" "$APP_DIR/host/bug-reporter-host.mjs"
} > "$LAUNCHER"
chmod 755 "$LAUNCHER"

EXT_ID="$("$NODE" "$HERE/lib/extension-id.mjs" "$REPO/extension/manifest.json")"

# ---- native messaging manifests ----
if [ "$(uname)" = "Darwin" ]; then
  AS="$HOME/Library/Application Support"
  BROWSERS=("$AS/Google/Chrome" "$AS/Google/Chrome Beta" "$AS/Google/Chrome Dev" "$AS/Google/Chrome Canary" "$AS/Google/Chrome for Testing" "$AS/Chromium" "$AS/BraveSoftware/Brave-Browser" "$AS/Microsoft Edge")
else
  C="${XDG_CONFIG_HOME:-$HOME/.config}"
  BROWSERS=("$C/google-chrome" "$C/google-chrome-beta" "$C/google-chrome-unstable" "$C/google-chrome-for-testing" "$C/chromium" "$C/BraveSoftware/Brave-Browser" "$C/microsoft-edge")
fi

REGISTERED=()
for base in "${BROWSERS[@]}"; do
  case "$base" in */Chromium|*/chromium) ;; *) [ -d "$base" ] || continue ;; esac
  mkdir -p "$base/NativeMessagingHosts"
  "$NODE" -e '
const fs = require("fs");
const [file, path, id] = process.argv.slice(1);
fs.writeFileSync(file, JSON.stringify({
  name: "com.egov.bug_reporter",
  description: "eGov Bug Reporter helper (gh + Claude Code)",
  path,
  type: "stdio",
  allowed_origins: ["chrome-extension://" + id + "/"]
}, null, 2) + "\n");
' "$base/NativeMessagingHosts/$HOST_NAME.json" "$LAUNCHER" "$EXT_ID"
  REGISTERED+=("$(basename "$base")")
done
echo
ok "Helper registered for: ${REGISTERED[*]}"
ok "Extension ID: $EXT_ID"

if [ "$INSTALL_SKILL" = "1" ]; then
  mkdir -p "$HOME/.claude/skills"
  ln -sfn "$REPO/skill/log-issue-extension" "$HOME/.claude/skills/log-issue-extension"
  ok "Linked the drafting skill into ~/.claude/skills/log-issue-extension"
fi

echo
echo "Next:"
echo "  1. chrome://extensions → turn on Developer mode → Load unpacked → pick: $REPO/extension"
echo "  2. The extension opens its setup page: check the helper is green, then add your project board links."
if [ "$PROBLEMS" = "1" ]; then
  echo
  warn "Fix the items marked above, then re-run this script."
fi
