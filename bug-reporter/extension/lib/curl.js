// Builds a cURL command in the style of DevTools "Copy as cURL (bash)".
// Nothing is redacted: the request goes into the issue as captured.

export function shellQuote(value) {
  const s = String(value);
  // Control characters or newlines: use ANSI-C quoting like DevTools does.
  if (/[\u0000-\u001f\u007f]/.test(s)) {
    const escaped = s
      .replace(/\\/g, '\\\\')
      .replace(/'/g, "\\'")
      .replace(/\n/g, '\\n')
      .replace(/\r/g, '\\r')
      .replace(/\t/g, '\\t')
      .replace(/[\u0000-\u001f\u007f]/g, (c) => '\\x' + c.charCodeAt(0).toString(16).padStart(2, '0'));
    return `$'${escaped}'`;
  }
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

function headerEntries(headers) {
  if (!headers) return [];
  if (Array.isArray(headers)) return headers.filter((h) => Array.isArray(h) && h.length >= 2);
  return Object.entries(headers);
}

/**
 * @param {{method?:string,url:string,reqHeaders?:object|Array,reqBody?:string|null,
 *          reqBodyKind?:string,reqFormData?:Array}} call
 */
export function toCurl(call) {
  const method = (call.method || 'GET').toUpperCase();
  const parts = [`curl ${shellQuote(call.url)}`];
  const hasBody = call.reqBodyKind === 'formdata' ? Array.isArray(call.reqFormData) && call.reqFormData.length > 0
    : call.reqBody != null && call.reqBody !== '';

  // --data-raw / -F imply POST, so -X is only needed for other methods.
  if ((method !== 'GET' && !hasBody) || (hasBody && method !== 'POST')) {
    parts.push(`-X ${shellQuote(method)}`);
  }
  for (const [k, v] of headerEntries(call.reqHeaders)) {
    // multipart boundaries are regenerated by curl -F
    if (call.reqBodyKind === 'formdata' && /^content-type$/i.test(k)) continue;
    parts.push(`-H ${shellQuote(`${k}: ${v}`)}`);
  }
  if (hasBody) {
    if (call.reqBodyKind === 'formdata') {
      for (const entry of call.reqFormData) {
        if (entry.file) {
          const type = entry.file.type ? `;type=${entry.file.type}` : '';
          parts.push(`-F ${shellQuote(`${entry.name}=@${entry.file.name || 'file'}${type}`)}`);
        } else {
          parts.push(`-F ${shellQuote(`${entry.name}=${entry.value ?? ''}`)}`);
        }
      }
    } else if (call.reqBodyKind === 'binary') {
      parts.push(`--data-binary ${shellQuote(call.reqBody)}`);
    } else {
      parts.push(`--data-raw ${shellQuote(call.reqBody)}`);
    }
  }
  return parts.join(' \\\n  ');
}
